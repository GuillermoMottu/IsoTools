import assert from 'node:assert/strict'
import { evaluationReducer as reduce, evaluateAfterPause } from '../demo-frontend/src/useToolEvaluation.js'
const initial = { input: { actual: 28 }, response: null, loading: false, error: '', dirty: false, requestId: null }
const started = reduce(initial, { type: 'start', id: 1 })
const completed = reduce(started, { type: 'success', id: 1, response: { result: { status: 'on_track' } } })
assert.equal(completed.response.result.status, 'on_track')
const edited = reduce(completed, { type: 'edit', input: current => ({ ...current, actual: 0 }) })
assert.equal(edited.response, null)
assert.equal(edited.input.actual, 0)
assert.equal(edited.dirty, true)
const changedDuringRequest = reduce(started, { type: 'edit', input: { actual: 0 } })
assert.equal(reduce(changedDuringRequest, { type: 'success', id: 1, response: completed.response }), changedDuringRequest)
assert.equal(reduce(changedDuringRequest, { type: 'error', id: 1, error: 'stale' }), changedDuringRequest)
const newer = reduce(changedDuringRequest, { type: 'start', id: 2 })
assert.equal(reduce(newer, { type: 'success', id: 1, response: completed.response }), newer)
const failed = reduce(newer, { type: 'error', id: 2, error: 'Network error' })
assert.equal(failed.loading, false)
assert.equal(failed.response, null)
assert.equal(failed.error, 'Network error')
const retried = reduce(failed, { type: 'start', id: 3 })
assert.equal(retried.error, '')
const success = reduce(retried, { type: 'success', id: 3, response: { result: { status: 'delayed' } } })
assert.equal(success.dirty, false)
assert.equal(success.response.result.status, 'delayed')
console.log('Frontend evaluation state smoke OK')
const capture = { ...initial, input: { metrics: [{ metric_id: 'A', name: 'Original', unit: 'items', weight: 1 }, { metric_id: 'B' }], milestones: [{ milestone_id: 'M1' }, { milestone_id: 'M2' }] }, response: completed.response }
const metricEdited = reduce(capture, { type: 'edit', input: current => ({ ...current, metrics: current.metrics.map((metric, index) => index === 0 ? { ...metric, name: 'Temperatura', unit: 'celsius', weight: 2 } : metric) }) })
assert.equal(metricEdited.response, null)
assert.equal(metricEdited.input.metrics[0].unit, 'celsius')
assert.equal(metricEdited.input.metrics[0].weight, 2)
const removed = reduce(metricEdited, { type: 'edit', input: current => ({ ...current, metrics: current.metrics.filter((metric, index) => index !== 1), milestones: current.milestones.filter((milestone, index) => index !== 0) }) })
assert.equal(removed.input.metrics[0].name, 'Temperatura')
assert.equal(removed.input.metrics.length, 1)
assert.equal(removed.input.milestones[0].milestone_id, 'M2')
console.log('Capture editing/removal state smoke OK')
const replaced = reduce(capture, { type: 'replace', input: { metrics: [] }, scenario: 'critical' })
assert.equal(replaced.response, null)
assert.equal(replaced.backup.input, capture.input)
assert.equal(replaced.backup.scenario, 'critical')
const restored = reduce(replaced, { type: 'undo' })
assert.equal(restored.input, capture.input)
assert.equal(restored.backup, null)
assert.equal(restored.response, null)
assert.equal(reduce(restored, { type: 'success', id: 99, response: completed.response }), restored)
console.log('Example replacement/recovery smoke OK')

let calls = []
const cancel = evaluateAfterPause(() => calls.push('obsolete'), 15)
cancel()
evaluateAfterPause(() => calls.push('latest'), 15)
await new Promise(resolve => setTimeout(resolve, 40))
assert.deepEqual(calls, ['latest'])
const cancelUnmounted = evaluateAfterPause(() => calls.push('unmounted'), 15)
cancelUnmounted()
await new Promise(resolve => setTimeout(resolve, 40))
assert.deepEqual(calls, ['latest'])
console.log('Automatic evaluation pause/cancellation smoke OK')
